#!/usr/bin/env python3
"""
Build the offline web bundle for the native apps (Capacitor, see apps/README.md).

Copies static/studio/** into apps/www/studio/, writes a standalone apps/www/index.html
derived from templates/studio/index.html (Django tags resolved, server-only parts removed)
and inlines the music catalogue as <script type="application/json" id="catalog-data">,
so the app runs fully offline without any server.

Catalogue sources (the catalogue holds music formulas only, no personal data):
  default        load fixtures/studio_music_data.json into an in-memory SQLite database
                 and run views_studio.build_catalog() on it (no project database needed)
  --from-db      run build_catalog() against the database configured in the project
                 settings (same result as `manage.py shell` -> build_catalog())
  --catalog F    use an existing JSON export, e.g. a saved copy of /api/catalog/

App-build differences from the web Studio (the web templates are not changed):
  - no donate link, no "Classic version" link, no service worker, no PWA manifest
  - About and Impressum & Privacy link to SITE_URL and open in the system browser
  - a Content-Security-Policy that only allows the bundle itself (no third-party requests)
  - apps/www/app.css adds safe-area padding for notches and system bars

Run with a Python environment that has the project requirements installed:
    python scripts/build_app_bundle.py [--out apps/www]
"""
import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TEMPLATE = REPO / 'templates' / 'studio' / 'index.html'
STATIC = REPO / 'static'
FIXTURE = REPO / 'fixtures' / 'studio_music_data.json'
DEFAULT_OUT = REPO / 'apps' / 'www'

SITE_URL = 'https://fretboard.schoensgibl.com'

# Files under static/studio/ that the app does not need
SKIP_STUDIO_FILES = {'manifest.webmanifest'}
SKIP_STUDIO_SUFFIXES = ('.test.mjs',)

CSP = ("default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; "
       "img-src 'self' data:; font-src 'self'; connect-src 'self'; media-src 'self' data: blob:; "
       "object-src 'none'; base-uri 'none'; form-action 'none'")

APP_CSS = """\
/* App-only additions (generated by scripts/build_app_bundle.py). Keeps content clear of the
   notch, home indicator and Android system bars; --safe-area-inset-* is set by Capacitor on
   Android WebViews that lack env(safe-area-inset-*). */
:root {
  --app-inset-top: var(--safe-area-inset-top, env(safe-area-inset-top, 0px));
  --app-inset-right: var(--safe-area-inset-right, env(safe-area-inset-right, 0px));
  --app-inset-bottom: var(--safe-area-inset-bottom, env(safe-area-inset-bottom, 0px));
  --app-inset-left: var(--safe-area-inset-left, env(safe-area-inset-left, 0px));
}
body {
  padding: var(--app-inset-top) var(--app-inset-right) var(--app-inset-bottom) var(--app-inset-left);
}
/* Opaque strip behind the status bar; the sticky top bar docks below it */
body::before {
  content: ''; position: fixed; z-index: 11; top: 0; left: 0; right: 0;
  height: var(--app-inset-top); background: var(--bg);
}
.topbar { top: var(--app-inset-top); }
.toast { margin-bottom: var(--app-inset-bottom); }
"""


def setup_django(from_db):
    sys.path.insert(0, str(REPO))
    os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'fretboard.settings')
    from django.conf import settings
    if not from_db:
        settings.DATABASES = {'default': {'ENGINE': 'django.db.backends.sqlite3', 'NAME': ':memory:'}}
    settings.CACHES = {'default': {'BACKEND': 'django.core.cache.backends.dummy.DummyCache'}}
    settings.LOGGING_CONFIG = None
    import django
    django.setup()
    return settings


def load_fixture_into_memory_db():
    from django.apps import apps
    from django.core.management import call_command
    from django.db import connection
    with connection.schema_editor() as editor:
        for model in apps.get_models():
            if model._meta.managed and not model._meta.proxy:
                editor.create_model(model)
    call_command('loaddata', str(FIXTURE), verbosity=0)


def get_catalog(args):
    if args.catalog:
        return json.loads(Path(args.catalog).read_text(encoding='utf-8'))
    if not args.from_db:
        load_fixture_into_memory_db()
    from positionfinder.views_studio import build_catalog
    return build_catalog()


def replace_once(html, old, new, label):
    count = html.count(old)
    if count != 1:
        raise SystemExit(f'build_app_bundle: expected exactly one "{label}" in {TEMPLATE.name}, found {count}')
    return html.replace(old, new)


def sub_once(html, pattern, repl, label, flags=0):
    result, count = re.subn(pattern, repl, html, flags=flags)
    if count != 1:
        raise SystemExit(f'build_app_bundle: expected exactly one "{label}" in {TEMPLATE.name}, found {count}')
    return result


def external_link(path, text):
    return f'<a href="{SITE_URL}{path}" target="_blank" rel="noopener">{text}</a>'


def build_index(catalog, version):
    from django.utils.html import json_script

    html = TEMPLATE.read_text(encoding='utf-8')

    html = replace_once(html, '{% load static %}', '', 'load static')
    html = replace_once(html, '<meta charset="utf-8">',
                        f'<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="{CSP}">',
                        'charset meta')

    # Head elements that only make sense for the hosted website
    html = sub_once(html, r'\n[ \t]*<link rel="canonical"[^\n]*', '', 'canonical link')
    html = re.sub(r'\n[ \t]*<meta (?:property="og:|name="twitter:)[^\n]*', '', html)
    html = replace_once(html, '\n  {% include "favicon.html" %}', '', 'favicon include')
    html = sub_once(html, r'\n[ \t]*<link rel="manifest"[^\n]*', '', 'manifest link')
    html = sub_once(html, r'\n[ \t]*<link rel="apple-touch-icon"[^\n]*', '', 'apple-touch-icon link')

    # {{ var|default:"text" }} -> text
    html = re.sub(r'\{\{\s*\w+\|default:(["\'])(.*?)\1\s*\}\}', r'\2', html)
    html = html.replace('{{ APP_VERSION }}', version)
    # Bundle mirrors static/ so static paths stay relative
    html = re.sub(r'\{% static [\'"]([^\'"]+)[\'"] %\}', r'\1', html)

    html = replace_once(html, '<link rel="stylesheet" href="studio/studio.css?v=' + version + '">',
                        '<link rel="stylesheet" href="studio/studio.css?v=' + version + '">\n'
                        '  <link rel="stylesheet" href="app.css?v=' + version + '">', 'stylesheet link')

    html = replace_once(html, "href=\"{% url 'fretboard' %}\"", 'href="index.html"', 'brand link')
    html = sub_once(html, r'<p class="noscript">.*?</p>',
                    '<p class="noscript">Guitar Positions needs JavaScript.</p>', 'noscript text', re.S)

    # Footer: keep About and Impressum (system browser), drop Classic version and donate
    html = replace_once(html, "<a href=\"{% url 'about' %}\">About</a>",
                        external_link('/about/', 'About'), 'about link')
    html = replace_once(html, "<a href=\"{% url 'impressum' %}\">Impressum &amp; Privacy</a>",
                        external_link('/impressum/', 'Impressum &amp; Privacy'), 'impressum link')
    html = sub_once(html, r'\n[ \t]*<a href="\{% url \'fretboard_classic\' %\}">Classic version</a>', '',
                    'classic link')
    html = sub_once(html, r'\n[ \t]*\{% if STRIPE_DONATE_URL %\}.*?\{% endif %\}', '', 'donate link')

    html = replace_once(html, '{{ catalog_json|json_script:"catalog-data" }}',
                        str(json_script(catalog, 'catalog-data')), 'catalog json_script')
    html = replace_once(html, '{{ legacy_state_json|json_script:"legacy-state" }}',
                        str(json_script({}, 'legacy-state')), 'legacy-state json_script')

    # The native shell serves the bundle itself; no service worker in the app
    html = sub_once(html, r'\n[ \t]*<script>\s*// Offline support\..*?</script>', '', 'service worker script', re.S)

    leftovers = re.findall(r'\{[%{#].*?[%}#]\}', html)
    if leftovers:
        raise SystemExit(f'build_app_bundle: unresolved template tags: {leftovers[:5]}')
    for forbidden in ('Classic version', 'STRIPE', 'serviceWorker', 'manifest.webmanifest'):
        if forbidden in html:
            raise SystemExit(f'build_app_bundle: "{forbidden}" is still in the app index.html')
    return html


def copy_static(out):
    studio_src = STATIC / 'studio'
    for src in sorted(studio_src.rglob('*')):
        if src.is_dir() or src.name in SKIP_STUDIO_FILES or src.name.endswith(SKIP_STUDIO_SUFFIXES):
            continue
        dest = out / 'studio' / src.relative_to(studio_src)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)

    # Assets referenced from studio.css via url(...), e.g. ../fonts/dosis/*.ttf
    css = (studio_src / 'studio.css').read_text(encoding='utf-8')
    for _, ref in re.findall(r'url\(\s*([\'"]?)(.*?)\1\s*\)', css):
        if ref.startswith('data:'):
            continue  # inline, no request
        if ref.startswith(('http:', 'https:', '//')):
            raise SystemExit(f'build_app_bundle: studio.css references a non-bundled asset: {ref}')
        src = (studio_src / ref).resolve()
        if not src.is_file() or STATIC.resolve() not in src.parents:
            raise SystemExit(f'build_app_bundle: studio.css asset not found under static/: {ref}')
        dest = out / src.relative_to(STATIC.resolve())
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--out', default=str(DEFAULT_OUT), help='output folder (default: apps/www)')
    source = parser.add_mutually_exclusive_group()
    source.add_argument('--from-db', action='store_true', help='use the database from the project settings')
    source.add_argument('--catalog', metavar='FILE', help='use a catalogue JSON export instead of Django')
    args = parser.parse_args()

    settings = setup_django(args.from_db)
    version = str(getattr(settings, 'VERSION', '0'))
    catalog = get_catalog(args)
    if not catalog.get('scales') or not catalog.get('chords'):
        raise SystemExit('build_app_bundle: the catalogue is empty; check the catalogue source')

    out = Path(args.out).resolve()
    if out.exists():
        # Only ever replace a previous bundle, never an unrelated folder
        if out == REPO or out in REPO.parents or (any(out.iterdir()) and not (out / 'index.html').is_file()):
            raise SystemExit(f'build_app_bundle: refusing to replace {out}; it does not look like an app bundle')
        shutil.rmtree(out)
    out.mkdir(parents=True)
    copy_static(out)
    (out / 'app.css').write_text(APP_CSS, encoding='utf-8')
    (out / 'index.html').write_text(build_index(catalog, version), encoding='utf-8')

    print(f'App bundle written to {out} (v{version}: {len(catalog["scales"])} scales, '
          f'{len(catalog["arpeggios"])} arpeggios, {len(catalog["chords"])} chords)')


if __name__ == '__main__':
    main()
